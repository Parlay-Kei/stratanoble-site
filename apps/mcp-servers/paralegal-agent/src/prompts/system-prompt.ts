/**
 * Get the system prompt with optional customizations
 */
export function getSystemPrompt(options?: {
  jurisdiction?: string;
  businessContext?: string;
}): string {
  let prompt = PARALEGAL_SYSTEM_PROMPT;

  if (options?.jurisdiction && options.jurisdiction !== 'US-NV') {
    prompt += `\n\n## JURISDICTION OVERRIDE\nThis engagement uses ${options.jurisdiction} as the governing jurisdiction instead of the default US-NV. Apply jurisdiction-specific templates and clauses where available.`;
  }

  if (options?.businessContext) {
    prompt += `\n\n## ADDITIONAL BUSINESS CONTEXT\n${options.businessContext}`;
  }

  return prompt;
}

