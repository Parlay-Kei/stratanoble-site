import { BrowserOperator } from './browser-operator.js';

async function testBasicNavigation() {
  console.log('\n=== TEST: Basic Navigation with Proof Capture ===\n');

  const operator = new BrowserOperator();
  await operator.initialize({
    headless: false,
    slowMo: 200
  });

  const executor = operator.executor;

  try {
    // Initialize browser
    await executor.initialize('test-session');

    // Navigate to example site
    await executor.navigate('https://example.com');

    // Capture proof
    await executor.captureProof('example_page', {
      test: 'basic_navigation',
      timestamp: new Date().toISOString()
    });

    // Generate proof pack
    const proofPack = await executor.generateProofPack(
      'Test: Basic Navigation',
      'OCS-BO-TEST-001'
    );

    console.log('✅ Basic navigation test completed');
    console.log(`Proof pack generated: ${proofPack.markdown}`);

    return proofPack;

  } finally {
    await executor.close();
  }
}

async function testFormInteraction() {
  console.log('\n=== TEST: Form Interaction with Before/After ===\n');

  const operator = new BrowserOperator();
  await operator.initialize({
    headless: false,
    slowMo: 300
  });

  const executor = operator.executor;

  try {
    // Initialize browser
    await executor.initialize('form-test');

    // Navigate to test form (using httpbin for testing)
    await executor.navigate('https://httpbin.org/forms/post');

    // Capture before state
    await executor.captureProof('before_form_fill', {
      state: 'empty_form'
    });

    // Fill form fields
    await executor.executeAction('fill', 'input[name="custname"]', {
      value: 'Test Customer'
    });

    await executor.executeAction('fill', 'input[name="custtel"]', {
      value: '555-1234'
    });

    await executor.executeAction('fill', 'textarea[name="comments"]', {
      value: 'This is a test comment generated by Browser Operator v1.0'
    });

    await executor.executeAction('select', 'select[name="size"]', {
      value: 'medium'
    });

    await executor.executeAction('check', 'input[value="bacon"]');
    await executor.executeAction('check', 'input[value="cheese"]');

    // Capture after state
    await executor.captureProof('after_form_fill', {
      state: 'filled_form',
      fields: ['custname', 'custtel', 'comments', 'size', 'toppings']
    });

    // Generate proof pack
    const proofPack = await executor.generateProofPack(
      'Test: Form Interaction',
      'OCS-BO-TEST-002'
    );

    console.log('✅ Form interaction test completed');
    console.log(`Proof pack generated: ${proofPack.markdown}`);

    return proofPack;

  } finally {
    await executor.close();
  }
}

async function testSessionPersistence() {
  console.log('\n=== TEST: Session Persistence ===\n');

  const operator = new BrowserOperator();
  await operator.initialize({
    headless: false,
    slowMo: 200
  });

  const sessionHandler = operator.sessionHandler;

  try {
    // Create a session
    const session1 = await sessionHandler.createSession('test', 'user1', {
      testData: 'session_test'
    });

    console.log(`Created session: ${session1.id}`);

    // Store some cookies (mock data)
    await sessionHandler.storeCookies(session1.id, [
      {
        name: 'test_session',
        value: 'abc123',
        domain: '.example.com',
        path: '/',
        expires: -1,
        httpOnly: false,
        secure: false,
        sameSite: 'Lax'
      }
    ]);

    // Retrieve session
    const retrievedSession = await sessionHandler.getSession('test', 'user1');

    if (retrievedSession && retrievedSession.cookies.length > 0) {
      console.log('✅ Session persistence test passed');
      console.log(`Session cookies: ${retrievedSession.cookies.length}`);
    } else {
      console.log('❌ Session persistence test failed');
    }

    // Cleanup
    await sessionHandler.cleanupSessions();

  } catch (error) {
    console.error('Session test error:', error.message);
  }
}

async function generateDemoProofPack() {
  console.log('\n=== DEMO: Complete Proof Pack Generation ===\n');

  const operator = new BrowserOperator();
  await operator.initialize({
    headless: false,
    slowMo: 100,
    recordVideo: true
  });

  const executor = operator.executor;

  try {
    // Initialize browser
    await executor.initialize('demo-proof');

    // Simulate a complete workflow
    console.log('1. Starting session...');
    await executor.navigate('https://www.example.com');

    console.log('2. Capturing initial state...');
    await executor.captureProof('initial_state', {
      page: 'example.com',
      title: await executor.page.title()
    });

    // Simulate navigation
    console.log('3. Performing navigation...');
    await executor.navigate('https://www.iana.org/domains/reserved');

    await executor.captureProof('after_navigation', {
      page: 'iana.org',
      title: await executor.page.title()
    });

    // Look for content
    console.log('4. Verifying content...');
    await executor.waitFor({
      type: 'text',
      value: 'reserved'
    });

    await executor.captureProof('content_verified', {
      verification: 'success',
      content: 'Found reserved domains information'
    });

    // Generate comprehensive proof pack
    console.log('5. Generating proof pack...');
    const proofPack = await executor.generateProofPack(
      'Demo: Complete Browser Automation Workflow',
      'OCS-BO-DEMO-001'
    );

    console.log('\n✅ Demo proof pack generated successfully!');
    console.log(`\nProof Pack Details:`);
    console.log(`- JSON: ${proofPack.json}`);
    console.log(`- Markdown: ${proofPack.markdown}`);
    console.log(`- Total Events: ${proofPack.proofPack.summary.totalEvents}`);
    console.log(`- Screenshots: ${proofPack.proofPack.summary.screenshots}`);
    console.log(`- URLs Visited: ${proofPack.proofPack.summary.urls.length}`);
    console.log(`- Duration: ${proofPack.proofPack.duration}`);

    return proofPack;

  } finally {
    await executor.close();
  }
}

