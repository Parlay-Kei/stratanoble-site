-- =============================================================================
-- TRIGGERS FOR UPDATED_AT
-- =============================================================================

create or replace function finance.update_updated_at_column()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger update_segments_updated_at
  before update on finance.segments
  for each row execute function finance.update_updated_at_column();

create trigger update_metric_definitions_updated_at
  before update on finance.metric_definitions
  for each row execute function finance.update_updated_at_column();

create trigger update_agent_schedules_updated_at
  before update on finance.agent_schedules
  for each row execute function finance.update_updated_at_column();

create trigger update_rulesets_updated_at
  before update on finance.rulesets
  for each row execute function finance.update_updated_at_column();
